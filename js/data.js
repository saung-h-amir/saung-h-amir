export function getMenuPosCategory(item) {
  if (!item) return 'Lauk';
  if (item.customCategory) return item.customCategory;

  const rawCat = String(item.posCategory || item.category || '').toLowerCase();
  const name = String(item.name || '').toLowerCase();

  // 1. Nasi
  if (rawCat.includes('nasi') || name.includes('nasi') || name.includes('liwet') || name.includes('bakul')) {
    return 'Nasi';
  }

  // 2. Minuman
  if (
    rawCat.includes('minum') ||
    rawCat.includes('jus') ||
    name.startsWith('es ') ||
    name.includes('es ') ||
    name.includes(' jus') ||
    name.includes('teh') ||
    name.includes('kopi') ||
    name.includes('jeruk') ||
    name.includes('kelapa') ||
    name.includes('aqua') ||
    name.includes('mineral') ||
    name.includes('soda')
  ) {
    return 'Minuman';
  }

  // 3. Sambal
  if (rawCat.includes('sambal') || name.includes('sambal') || name.includes('sambel')) {
    return 'Sambal';
  }

  // 4. Pepes & Ikan Asin
  if (
    rawCat.includes('pepes') ||
    name.includes('pepes') ||
    name.includes('ikan asin') ||
    name.includes('jambal') ||
    name.includes('peda') ||
    name.includes('sepat')
  ) {
    return 'Pepes & Ikan Asin';
  }

  // 5. Sayur
  if (
    rawCat.includes('sayur') ||
    rawCat.includes('tumis') ||
    name.includes('sayur') ||
    name.includes('tumis') ||
    name.includes('kangkung') ||
    name.includes('genjer') ||
    name.includes('kembang paya') ||
    name.includes('jantung pisang') ||
    name.includes('lalap')
  ) {
    return 'Sayur';
  }

  // 6. Lauk (Ayam, Daging, Gurame, Ikan, Seafood, Paket Hemat, Gorengan, Jengkol & Pete)
  return 'Lauk';
}

